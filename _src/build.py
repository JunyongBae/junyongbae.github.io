#!/usr/bin/env python3
"""Build the NAIRO Lab site.

    python _src/build.py

Reads _src/data/*.yml (content) and _src/templates/*.html (layout) and writes the
public pages and sitemap.xml to the site root. Generated pages carry a marker comment;
never edit them by hand, edit the data or templates and rebuild.

Also handled automatically:
  - publication numbers [J..]/[C..] and the counts shown next to section titles
  - the ?v= cache-busting version on style.css / site.js (a hash of their contents)
  - bold PI name in author lists, current-page highlighting in the menu
  - pages switched off in pages.yml are removed (file, menu entry, sitemap entry)
  - sitemap <lastmod> only moves for pages whose output actually changed
"""
import datetime
import hashlib
import pathlib
import re
import sys

import yaml
from jinja2 import Environment, FileSystemLoader, select_autoescape
from markupsafe import Markup, escape

SRC = pathlib.Path(__file__).resolve().parent
ROOT = SRC.parent
MARKER = "<!-- Generated by _src/build.py"
DATA_FILES = ["site", "pages", "home", "news", "professor", "members", "research", "projects", "publications"]


def load(name):
    path = SRC / "data" / f"{name}.yml"
    try:
        return yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as e:
        sys.exit(f"[build] YAML error in {path.relative_to(ROOT)}:\n{e}")


def asset_version():
    h = hashlib.sha1()
    for rel in ("assets/style.css", "assets/site.js"):
        h.update((ROOT / rel).read_bytes())
    return h.hexdigest()[:8]


def prepare_publications(pubs):
    """Number journals/conferences newest-first across both sections and build the count labels."""
    cur, old = pubs["current"], pubs["before"]
    cur.setdefault("conferences", [])
    journals = cur["journals"] + old["journals"]
    confs = cur["conferences"] + old["conferences"]
    for i, p in enumerate(journals):
        p["no"] = len(journals) - i
        if p.get("status", "published") != "review":
            parts = [p["venue"]] + ([f"VOL {p['volume']}"] if p.get("volume") else []) + [str(p["year"])]
            p["meta"] = " · ".join(parts).upper()
    for i, c in enumerate(confs):
        c["no"] = len(confs) - i

    def plural(n, word):
        return f"{n} {word}{'' if n == 1 else 's'}"

    n_review = sum(1 for p in cur["journals"] if p.get("status") == "review")
    n_pub = len(cur["journals"]) - n_review
    bits = ([plural(n_pub, "published article")] if n_pub else []) + ([f"{n_review} under review"] if n_review else [])
    if cur["conferences"]:
        bits.append(plural(len(cur["conferences"]), "conference presentation"))
    cur["count_label"] = " · ".join(bits)
    old["count_label"] = (f"{plural(len(old['journals']), 'journal article')} · "
                          f"{plural(len(old['conferences']), 'conference presentation')}")
    awarded = sum(1 for c in old["conferences"] if c.get("award"))
    old["conf_label"] = f"{len(old['conferences'])} selected" + (f" · {awarded} awarded" if awarded else "")
    return pubs


def build_nav(nav, enabled, current):
    out = []
    for item in nav:
        if item.get("children"):
            kids = [c for c in item["children"] if c["page"] in enabled]
            if kids:
                out.append({**item, "children": kids, "current": any(c["page"] == current for c in kids)})
        elif item["page"] in enabled:
            out.append(item)
    return out


def main():
    data = {name: load(name) for name in DATA_FILES}
    site = data["site"]
    data["publications"] = prepare_publications(data["publications"])
    version = asset_version()

    env = Environment(loader=FileSystemLoader(SRC / "templates"), autoescape=select_autoescape(["html"]),
                      trim_blocks=True, lstrip_blocks=True, keep_trailing_newline=True)
    pi = escape(site["pi"])
    env.filters["pi"] = lambda authors: Markup(str(escape(authors)).replace(str(pi), f"<b>{pi}</b>"))

    pages = data["pages"]
    enabled = {p["file"] for p in pages if p.get("enabled", True)}
    today = datetime.date.today().isoformat()
    old_lastmod = dict(re.findall(r"<loc>([^<]+)</loc>\s*<lastmod>([^<]+)</lastmod>",
                                  (ROOT / "sitemap.xml").read_text(encoding="utf-8"))) if (ROOT / "sitemap.xml").exists() else {}
    sitemap = []

    for p in pages:
        out = ROOT / p["file"]
        if p["file"] not in enabled:
            if out.exists() and MARKER in out.read_text(encoding="utf-8")[:400]:
                out.unlink()
                print(f"[build] removed {p['file']} (disabled)")
            continue
        url = site["base_url"] + ("" if p["file"] == "index.html" else p["file"])
        page = {"author": None, "robots": None, "og_type": None, **p, "url": url}
        html = env.get_template(p["template"]).render(
            page=page, site=site, nav=build_nav(site["nav"], enabled, p["file"]), version=version,
            **{k: v for k, v in data.items() if k not in ("site", "pages")})
        html = re.sub(r"\n{3,}", "\n\n", html)          # collapse blank-line runs left by template tags
        changed = not out.exists() or out.read_text(encoding="utf-8") != html
        if changed:
            out.write_text(html, encoding="utf-8", newline="\n")
        sitemap.append((url, today if changed or url not in old_lastmod else old_lastmod[url], p["file"]))
        print(f"[build] {'wrote ' if changed else 'same  '} {p['file']}")

    prio = {"index.html": ("weekly", "1.0"), "professor.html": ("monthly", "0.9"), "contact.html": ("yearly", "0.6")}
    lines = ['<?xml version="1.0" encoding="UTF-8"?>', '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for url, lastmod, f in sitemap:
        freq, pr = prio.get(f, ("monthly", "0.8"))
        lines += ["  <url>", f"    <loc>{url}</loc>", f"    <lastmod>{lastmod}</lastmod>",
                  f"    <changefreq>{freq}</changefreq>", f"    <priority>{pr}</priority>", "  </url>"]
    cv = site["base_url"] + data["professor"]["cv"]
    if (ROOT / data["professor"]["cv"]).exists():
        lines += ["  <url>", f"    <loc>{cv}</loc>", f"    <lastmod>{old_lastmod.get(cv, today)}</lastmod>",
                  "    <changefreq>monthly</changefreq>", "    <priority>0.5</priority>", "  </url>"]
    lines.append("</urlset>")
    (ROOT / "sitemap.xml").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"[build] sitemap.xml ({len(sitemap)} pages) · assets v={version}")


if __name__ == "__main__":
    main()
